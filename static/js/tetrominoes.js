function getRandomTetromino() {
    const types = Object.keys(TETROMINOES);
    const randomType = types[Math.floor(Math.random() * types.length)];
    return {
        type: randomType,
        ...TETROMINOES[randomType],
        rotation: 0,
        x: 3,
        y: 0
    };
}
